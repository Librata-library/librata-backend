@app.route("/add_student",methods=["GET","POST"])
@login_required
def add_student():
    message=""
    if request.method=="POST":
        vals=[request.form.get(k,"").strip() for k in ("name","guardian","mobile","seat","shift")]
        admission=request.form.get("admission_date") or date.today().isoformat()
        if not all(vals): message="All required fields must be filled."
        elif not vals[2].isdigit() or len(vals[2])!=10: message="Enter a valid 10-digit mobile number."
        elif vals[4] not in ("Morning","Evening"): message="Select a valid shift."
        else:
            with connect() as con:
                duplicate=con.execute("SELECT id FROM students WHERE seat=? AND shift=?",(vals[3],vals[4])).fetchone()
                if duplicate: message="This seat is already assigned in this shift."
                else:
                    con.execute(
                        """INSERT INTO students
                           (name,guardian,mobile,seat,shift,admission_date,status)
                           VALUES(?,?,?,?,?,?,?)""",
                        (*vals, admission, "Approved")
                    )
                    flash("Student added successfully."); return redirect("/students")
    return page("Add Student","STUDENT DIRECTORY","students",STUDENT_FORM+"<p style='color:#ff9aa5'>{{ message }}</p>",s=None,button="Save Student",today=date.today().isoformat(),message=message)

@app.route("/edit_student/<int:student_id>",methods=["GET","POST"])
@login_required
def edit_student(student_id):
    message=""
    with connect() as con:
        s=con.execute("SELECT * FROM students WHERE id=?",(student_id,)).fetchone()
        if not s: return redirect("/students")
        if request.method=="POST":
            vals=[request.form.get(k,"").strip() for k in ("name","guardian","mobile","seat","shift")]
            admission=request.form.get("admission_date") or date.today().isoformat()
            if not all(vals) or not vals[2].isdigit() or len(vals[2])!=10 or vals[4] not in ("Morning","Evening"):
                message="Please check the details. Mobile number must have 10 digits."
            else:
                duplicate=con.execute("SELECT id FROM students WHERE seat=? AND shift=? AND id!=?",(vals[3],vals[4],student_id)).fetchone()
                if duplicate: message="This seat is already assigned to another student in this shift."
                else:
                    con.execute("UPDATE students SET name=?,guardian=?,mobile=?,seat=?,shift=?,admission_date=? WHERE id=?",(*vals,admission,student_id))
                    flash("Student details updated."); return redirect("/students")
    return page("Edit Student","STUDENT DIRECTORY","students",STUDENT_FORM+"<p style='color:#ff9aa5'>{{ message }}</p>",s=s,button="Update Student",today=date.today().isoformat(),message=message)

