@app.route("/approve_student/<int:student_id>", methods=["POST"])
@login_required
def approve_student(student_id):
    seat = request.form.get("seat", "").strip()
    shift = request.form.get("shift", "").strip()

    if not seat or shift not in ("Morning", "Evening"):
        flash("Enter a valid seat number and shift.")
        return redirect("/pending_students")

    with connect() as con:
        student = con.execute(
            "SELECT id FROM students WHERE id=? AND status='Pending'",
            (student_id,)
        ).fetchone()

        if not student:
            flash("Pending student not found.")
            return redirect("/pending_students")

        duplicate = con.execute(
            "SELECT id FROM students WHERE seat=? AND shift=? AND id!=?",
            (seat, shift, student_id)
        ).fetchone()

        if duplicate:
            flash("This seat is already assigned in this shift.")
            return redirect("/pending_students")

        con.execute(
            """UPDATE students
               SET seat=?, shift=?, status='Approved'
               WHERE id=?""",
            (seat, shift, student_id)
        )

    flash("Student approved successfully.")
    return redirect("/pending_students")


