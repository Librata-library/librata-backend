@app.route("/api/student/register-fcm-token", methods=["POST"])
def register_fcm_token():
    student_auth = get_authenticated_student()

    if not student_auth:
        return jsonify({
            "success": False,
            "message": "Unauthorized. Please login again."
        }), 401

    data = request.get_json(silent=True) or {}
    token = (data.get("token") or "").strip()
    student_id = student_auth["id"]

    if len(token) < 20:
        return jsonify({
            "success": False,
            "message": "Invalid notification token"
        }), 400

    with connect() as con:
        con.execute(
            "DELETE FROM student_fcm_tokens WHERE token=? AND student_id!=?",
            (token, student_id)
        )

        con.execute("""
            INSERT INTO student_fcm_tokens(student_id, token)
            VALUES(?, ?)
            ON CONFLICT(student_id) DO UPDATE SET
                token=excluded.token,
                updated_at=CURRENT_TIMESTAMP
        """, (student_id, token))

    return jsonify({
        "success": True,
        "message": "Token registered"
    })

@app.route("/api/student/login", methods=["POST"])
def student_login():
    data = request.get_json(silent=True) or {}

    name = data.get("name", "").strip()
    mobile = data.get("mobile", "").strip()

    if not name or not mobile:
        return jsonify({
            "success": False,
            "message": "Name and mobile are required"
        }), 400

    if not mobile.isdigit() or len(mobile) != 10:
        return jsonify({
            "success": False,
            "message": "Invalid mobile number"
        }), 400

    with connect() as con:
        student = con.execute(
            """SELECT id, name, mobile, seat, shift, status
               FROM students
               WHERE LOWER(TRIM(name)) = LOWER(?)
               AND mobile = ?""",
            (name, mobile)
        ).fetchone()

    if not student:
        return jsonify({
            "success": False,
            "message": "Student not found. Contact Admin."
        }), 401

    status = student["status"]

    if status == "Pending":
        return jsonify({
            "success": False,
            "message": "Your registration is waiting for Admin approval."
        }), 403

    if status == "Rejected":
        return jsonify({
            "success": False,
            "message": "Your registration was rejected. Contact Admin."
        }), 403

    if status != "Approved":
        return jsonify({
            "success": False,
            "message": "Account status is invalid. Contact Admin."
        }), 403

    auth_token = create_student_token(student["id"])

    return jsonify({
        "success": True,
        "message": "Login successful",
        "auth_token": auth_token,
        "student": {
            "id": student["id"],
            "name": student["name"],
            "seat": student["seat"],
            "shift": student["shift"]
        }
    })

@app.route("/api/student/attendance", methods=["GET"])
def student_attendance():
    student_auth = get_authenticated_student()

    if not student_auth:
        return jsonify({
            "success": False,
            "message": "Unauthorized. Please login again."
        }), 401

    student_id = student_auth["id"]

    with connect() as con:
        records = con.execute("""
            SELECT attend_date, status
            FROM attendance
            WHERE student_id = ?
            ORDER BY attend_date DESC
        """, (student_id,)).fetchall()

    present = sum(1 for r in records if r["status"] == "Present")
    absent = sum(1 for r in records if r["status"] == "Absent")

    return jsonify({
        "success": True,
        "present": present,
        "absent": absent,
        "total": present + absent,
        "records": [
            {
                "date": r["attend_date"],
                "status": r["status"]
            }
            for r in records
        ]
    })

