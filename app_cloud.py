class HybridRow(dict):
    def __init__(self, columns, values):
        super().__init__(zip(columns, values))
        self.values_list = values

    def __getitem__(self, key):
        if isinstance(key, int):
            return self.values_list[key]
        return super().__getitem__(key)

def hybrid_row_factory(cursor):
    if cursor.description is None:
        return lambda values: values

    columns = [col.name for col in cursor.description]

    def make_row(values):
        return HybridRow(columns, values)

    return make_row

class DBConnection:
    def __init__(self):
        database_url = os.environ.get("DATABASE_URL")
        if not database_url:
            raise RuntimeError("DATABASE_URL is not configured")

        self.raw = psycopg.connect(
            database_url,
            row_factory=hybrid_row_factory
        )

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        try:
            if exc_type is None:
                self.raw.commit()
            else:
                self.raw.rollback()
        finally:
            self.raw.close()

    def execute(self, sql, params=()):
        sql = sql.replace("?", "%s")
        return self.raw.execute(sql, params)

def connect():
    return DBConnection()

def setup_database():
    with connect() as con:
        con.execute("""
            CREATE TABLE IF NOT EXISTS admins (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE,
                password TEXT
            )
        """)

        con.execute("""
            CREATE TABLE IF NOT EXISTS students (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                guardian TEXT NOT NULL,
                mobile TEXT NOT NULL,
                seat TEXT NOT NULL,
                shift TEXT NOT NULL
            )
        """)

        con.execute("""
            CREATE TABLE IF NOT EXISTS attendance (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id BIGINT NOT NULL,
                attend_date TEXT NOT NULL,
                status TEXT NOT NULL,
                UNIQUE(student_id, attend_date),
                FOREIGN KEY(student_id) REFERENCES students(id) ON DELETE CASCADE
            )
        """)

        con.execute("""
            CREATE TABLE IF NOT EXISTS fees (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id BIGINT NOT NULL,
                fee_month TEXT NOT NULL,
                amount DOUBLE PRECISION NOT NULL,
                paid DOUBLE PRECISION NOT NULL DEFAULT 0,
                status TEXT NOT NULL DEFAULT 'Unpaid',
                paid_date TEXT,
                UNIQUE(student_id, fee_month),
                FOREIGN KEY(student_id) REFERENCES students(id) ON DELETE CASCADE
            )
        """)

        con.execute("""
            CREATE TABLE IF NOT EXISTS books (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL,
                author TEXT DEFAULT '',
                quantity INTEGER NOT NULL DEFAULT 1,
                available INTEGER NOT NULL DEFAULT 1
            )
        """)

        con.execute("""
            CREATE TABLE IF NOT EXISTS book_issues (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                book_id BIGINT NOT NULL,
                student_id BIGINT NOT NULL,
                issue_date TEXT NOT NULL,
                return_date TEXT,
                status TEXT NOT NULL DEFAULT 'Issued',
                FOREIGN KEY(book_id) REFERENCES books(id),
                FOREIGN KEY(student_id) REFERENCES students(id) ON DELETE CASCADE
            )
        """)

        con.execute("""
            CREATE TABLE IF NOT EXISTS transactions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                kind TEXT NOT NULL,
                title TEXT NOT NULL,
                amount DOUBLE PRECISION NOT NULL,
                txn_date TEXT NOT NULL,
                note TEXT DEFAULT ''
            )
        """)

        con.execute("""
            CREATE TABLE IF NOT EXISTS notices (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL,
                body TEXT NOT NULL,
                created_at TEXT NOT NULL
            )
        """)

        con.execute("""
            CREATE TABLE IF NOT EXISTS student_fcm_tokens (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id BIGINT NOT NULL UNIQUE,
                token TEXT NOT NULL UNIQUE,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY(student_id) REFERENCES students(id) ON DELETE CASCADE
            )
        """)

        con.execute("""
            CREATE TABLE IF NOT EXISTS student_auth_tokens (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id BIGINT NOT NULL,
                token_hash TEXT NOT NULL UNIQUE,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY(student_id) REFERENCES students(id) ON DELETE CASCADE
            )
        """)

        if not con.execute(
            "SELECT id FROM admins WHERE username='admin'"
        ).fetchone():
            con.execute(
                "INSERT INTO admins(username, password) VALUES(?, ?)",
                ("admin", generate_password_hash("Librata@123"))
            )

