def create_student_token(student_id):
    token = secrets.token_urlsafe(32)
    token_hash = hashlib.sha256(token.encode()).hexdigest()

    with connect() as con:
        con.execute(
            "DELETE FROM student_auth_tokens WHERE student_id=?",
            (student_id,)
        )
        con.execute(
            "INSERT INTO student_auth_tokens(student_id, token_hash) VALUES(?, ?)",
            (student_id, token_hash)
        )

    return token


def get_authenticated_student():
    auth_header = request.headers.get("Authorization", "")

    if not auth_header.startswith("Bearer "):
        return None

    token = auth_header[7:].strip()

    if not token:
        return None

    token_hash = hashlib.sha256(token.encode()).hexdigest()

    with connect() as con:
        student = con.execute("""
            SELECT s.id, s.name, s.status
            FROM student_auth_tokens t
            JOIN students s ON s.id = t.student_id
            WHERE t.token_hash = ?
        """, (token_hash,)).fetchone()

    if not student or student["status"] != "Approved":
        return None

    return student

